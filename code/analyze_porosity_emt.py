"""Estimate ice porosity with Bruggeman effective-medium theory.

This workflow extracts drift-corrected THz optical constants, uses a fixed
solid-ice density of 0.917 g/cm^3, inverts the Bruggeman model, and
compares optical porosity with gravimetric porosity. Uncertainties are standard
uncertainties. The residual uncertainty includes the covariance generated by
using the same thickness input in both porosity estimates.
"""

from __future__ import annotations

import argparse
